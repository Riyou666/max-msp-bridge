// Run after live-smoke and live-regression, only on a disposable, explicit host.
import path from 'node:path';
import assert from 'node:assert/strict';
import {callTool} from './mcp-server.mjs';
const index=process.argv.indexOf('--patch');
if(!process.argv.includes('--demo')||index<0||!process.argv[index+1])throw Error('Requires --demo --patch <absolute test host>');
const expected=path.resolve(process.argv[index+1]).replaceAll('\\','/').toLowerCase();
const status=await callTool('max_status');assert.equal(status.version,'0.3.0');
const root=(await callTool('max_inspect',{session:status.session})).result;
assert.equal(path.resolve(root.filepath).replaceAll('\\','/').toLowerCase(),expected);
const context={session:status.session,scope:['workspace']};
const inspect=async()=> (await callTool('max_inspect',context)).result;
const mutate=async(name,args)=>callTool(name,{...context,...args,expectedRevision:(await inspect()).revision});
let graph=await inspect();
const unnamedCord=graph.connections.find(c=>c.source===null&&c.destination===null);
assert.ok(unnamedCord,'Run live-regression first');
const {sourceId,destinationId}=unnamedCord;
await mutate('max_disconnect',{sourceId,destinationId,outlet:0,inlet:0});
await mutate('max_connect',{sourceId,destinationId,outlet:0,inlet:0});
await mutate('max_setvalue',{objectId:sourceId,value:23});
graph=await inspect();assert.equal(Number(graph.objects.find(o=>o.id===destinationId).value),23);
assert.equal(graph.objects.find(o=>o.id===sourceId).varname,null);
assert.equal(graph.objects.find(o=>o.id===destinationId).varname,null);
await assert.rejects(()=>mutate('max_remove',{objectId:sourceId}),/only removes/);
const marker='codex-background-test-'+Date.now();
const printer=(await mutate('max_create',{name:'consoleProbe',object:'print',args:['bridge-background-test'],x:700,y:500})).result;
await mutate('max_send',{objectId:printer.id,selector:'list',args:[marker]});
const log=(await callTool('max_console',{session:status.session,limit:20,contains:marker})).result;
assert.ok(log.lines.some(line=>line.includes(marker)));
const settings=(await callTool('max_audio_status',{session:status.session,settings:['sr','sigvs','iovs','switch','overdrive']})).result;
assert.ok(settings.settings.every(s=>typeof s.value==='number'));
const current=settings.settings.find(s=>s.setting==='overdrive').value;
const noop=(await mutate('max_audio_set',{setting:'overdrive',value:current,expectedValue:current})).result;
assert.equal(noop.changed,false);
await assert.rejects(()=>mutate('max_audio_set',{setting:'overdrive',value:current,expectedValue:1-current}),/changed/);
const preferences=(await callTool('max_preferences',{session:status.session,names:['overdrive','setpollthrottle','not_a_preference']})).result;
assert.ok('setpollthrottle' in preferences.values);assert.ok(preferences.unavailable.includes('not_a_preference'));
await mutate('max_remove',{objectId:printer.id});
console.log(JSON.stringify({passed:true,unnamedIdWiring:true,unnamedIdValuePropagation:true,consoleMarkerRead:true,preferencesRead:true,audioStatusRead:true,audioSettingsChanged:false,computerUse:false}));
