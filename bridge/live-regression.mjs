import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {callTool} from './mcp-server.mjs';
import assert from 'node:assert/strict';
const patchArg=process.argv.indexOf('--patch');
if(!process.argv.includes('--demo')||patchArg<0||!process.argv[patchArg+1])throw Error('Requires --demo --patch <test patch>; run after live-smoke on an isolated demo.');
const expected=path.resolve(process.argv[patchArg+1]).replaceAll('\\','/').toLowerCase();
const status=await callTool('max_status');assert.equal(status.version,'0.3.0');
const ctx={session:status.session,scope:['workspace']};
const root=await callTool('max_inspect',{session:status.session});assert.equal(path.resolve(root.result.filepath).replaceAll('\\','/').toLowerCase(),expected,'Wrong host patch');
const inspect=async()=> (await callTool('max_inspect',ctx)).result;
const mutate=async(name,args)=>callTool(name,{...ctx,...args,expectedRevision:(await inspect()).revision});
for(const name of ['ownedReplacementProbe','manualFixture'])assert.ok(!(await inspect()).objects.some(o=>o.varname===name),'Fixture already exists; use a fresh demo');
await mutate('max_create',{name:'ownedReplacementProbe',object:'number',args:[],x:500,y:400});
await mutate('max_create',{name:'manualFixture',object:'v8',args:[fileURLToPath(new URL('./fixtures/manual-edit.js',import.meta.url)).replaceAll('\\','/')],x:500,y:350});
const original=(await inspect()).objects.find(o=>o.varname==='ownedReplacementProbe').id;
await mutate('max_send',{name:'manualFixture',selector:'bang',args:[]});
let state=await inspect();
const replacement=state.objects.find(o=>o.varname==='ownedReplacementProbe');assert.notEqual(replacement.id,original);
await assert.rejects(()=>mutate('max_remove',{name:'ownedReplacementProbe'}),/only removes/);
state=await inspect();assert.ok(state.objects.some(o=>o.id===replacement.id));
const unnamed=state.objects.filter(o=>o.varname===null);assert.equal(unnamed.length,2);
assert.notEqual(unnamed[0].id,unnamed[1].id);
assert.ok(state.connections.some(c=>c.source===null&&c.destination===null&&c.sourceId!==c.destinationId&&unnamed.some(o=>o.id===c.sourceId)&&unnamed.some(o=>o.id===c.destinationId)));
const stale=state.revision;
const beforeMove=state.objects.find(o=>o.varname==='demoOutput').rect;
await mutate('max_move',{name:'demoOutput',x:beforeMove[0]+20,y:beforeMove[1]});
await assert.rejects(()=>callTool('max_setvalue',{...ctx,name:'demoInput',value:999,expectedRevision:stale}),/State conflict/);
assert.equal(Number((await inspect()).objects.find(o=>o.varname==='demoOutput').value),42);
await mutate('max_remove',{name:'manualFixture'});
console.log(JSON.stringify({passed:true,liveReplacementProtected:true,liveUnnamedConnections:true,liveConflictRejected:true,audioTested:false}));
